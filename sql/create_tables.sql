BEGIN;

CREATE TABLE roles (
    role_id       smallint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name     varchar(40) NOT NULL UNIQUE,
    description   text
);

CREATE TABLE users (
    user_id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(60) NOT NULL UNIQUE,
    password_hash varchar(255) NOT NULL,
    full_name     varchar(160) NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    is_active     boolean NOT NULL DEFAULT true,
    role_id       smallint NOT NULL REFERENCES roles(role_id) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE categories (
    category_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL UNIQUE,
    description   text
);

CREATE TABLE sources (
    source_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(120) NOT NULL UNIQUE,
    source_type   varchar(40) NOT NULL,
    url           text,
    description   text,
    CONSTRAINT sources_url_format CHECK (url IS NULL OR url ~* '^https?://')
);

CREATE TABLE audiences (
    audience_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(100) NOT NULL UNIQUE,
    description   text
);

CREATE TABLE events (
    event_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(200) NOT NULL,
    description   text,
    event_date    timestamptz NOT NULL,
    location      varchar(200) NOT NULL,
    status        varchar(20) NOT NULL DEFAULT 'planned',
    organizer_id  bigint NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    category_id   bigint NOT NULL REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT events_status CHECK (status IN ('planned','ongoing','completed','cancelled'))
);

CREATE TABLE media (
    media_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title         varchar(200) NOT NULL,
    description   text,
    media_type    varchar(10) NOT NULL,
    file_path     text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    is_active     boolean NOT NULL DEFAULT true,
    added_by      bigint NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    category_id   bigint NOT NULL REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    source_id     bigint NOT NULL REFERENCES sources(source_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    event_id      bigint REFERENCES events(event_id) ON UPDATE CASCADE ON DELETE SET NULL,
    CONSTRAINT media_type_allowed CHECK (media_type IN ('image','video')),
    CONSTRAINT media_relative_path CHECK (file_path <> '' AND file_path !~ '^[A-Za-z]:[/\\\\]')
);

CREATE TABLE announcements (
    announcement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title           varchar(200) NOT NULL,
    content         text NOT NULL,
    start_date      date NOT NULL,
    end_date        date NOT NULL,
    is_active       boolean NOT NULL DEFAULT true,
    author_id       bigint NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    category_id     bigint NOT NULL REFERENCES categories(category_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    audience_id     bigint NOT NULL REFERENCES audiences(audience_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT announcements_date_order CHECK (end_date >= start_date)
);

CREATE TABLE playlists (
    playlist_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(160) NOT NULL UNIQUE,
    description   text,
    created_by    bigint NOT NULL REFERENCES users(user_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    is_active     boolean NOT NULL DEFAULT true,
    created_at    timestamptz NOT NULL DEFAULT now()
);

-- One playlist item displays exactly one content record. The separate nullable
-- FKs keep the requested Events/Media/Announcements relationships explicit.
CREATE TABLE playlist_items (
    item_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    playlist_id      bigint NOT NULL REFERENCES playlists(playlist_id) ON UPDATE CASCADE ON DELETE CASCADE,
    position         integer NOT NULL,
    display_duration integer NOT NULL,
    media_id         bigint REFERENCES media(media_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    announcement_id  bigint REFERENCES announcements(announcement_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    event_id         bigint REFERENCES events(event_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT playlist_items_position_positive CHECK (position > 0),
    CONSTRAINT playlist_items_duration_positive CHECK (display_duration > 0),
    CONSTRAINT playlist_items_unique_position UNIQUE (playlist_id, position),
    CONSTRAINT playlist_items_exactly_one_content CHECK (
        num_nonnulls(media_id, announcement_id, event_id) = 1
    )
);

CREATE TABLE displays (
    display_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(160) NOT NULL UNIQUE,
    location      varchar(200) NOT NULL,
    description   text,
    is_active     boolean NOT NULL DEFAULT true
);

CREATE TABLE schedules (
    schedule_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          varchar(160) NOT NULL,
    playlist_id   bigint NOT NULL REFERENCES playlists(playlist_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    display_id    bigint NOT NULL REFERENCES displays(display_id) ON UPDATE CASCADE ON DELETE RESTRICT,
    start_date    date NOT NULL,
    end_date      date NOT NULL,
    start_time    time NOT NULL,
    end_time      time NOT NULL,
    is_active     boolean NOT NULL DEFAULT true,
    CONSTRAINT schedules_date_order CHECK (end_date >= start_date),
    CONSTRAINT schedules_time_order CHECK (end_time > start_time)
);

CREATE INDEX events_date_idx ON events(event_date);
CREATE INDEX events_category_idx ON events(category_id);
CREATE INDEX media_type_active_idx ON media(media_type, is_active);
CREATE INDEX media_event_idx ON media(event_id);
CREATE INDEX announcements_active_dates_idx ON announcements(is_active, start_date, end_date);
CREATE INDEX playlist_items_media_idx ON playlist_items(media_id) WHERE media_id IS NOT NULL;
CREATE INDEX playlist_items_announcement_idx ON playlist_items(announcement_id) WHERE announcement_id IS NOT NULL;
CREATE INDEX playlist_items_event_idx ON playlist_items(event_id) WHERE event_id IS NOT NULL;
CREATE INDEX schedules_lookup_idx ON schedules(display_id, is_active, start_date, end_date, start_time, end_time);

COMMIT;
